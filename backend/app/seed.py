def seed(db: Session) -> None:
    deps = {n: Department(name=n) for n in DEPARTMENTS}
    db.add_all(deps.values())
    db.flush()
    users: dict[str, User] = {}
    pw = hash_password(DEMO_PASSWORD)
    for key, (name, pos, role, dep, is_head) in USERS.items():
        u = User(name=name, email=f"{key}@modus.demo", password_hash=pw, role=role, position=pos, department_id=deps[dep].id)
        db.add(u)
        users[key] = u
    db.flush()
    for key, (_, _, _, dep, is_head) in USERS.items():
        if is_head:
            deps[dep].head_id = users[key].id
    users["nomen"].deputy_id = users["purch_head"].id  # пример замещения
    cats = {}
    for name, (desc, resp, sla) in CATEGORIES.items():
        cats[name] = Category(name=name, description=desc, responsible_id=users[resp].id, sla_days=sla)
        db.add(cats[name])
    db.flush()

    t = now()
    for idx, (typ, cat, author, prio, status, title, text, assignee, note, days) in enumerate(A, start=1):
        created = t - timedelta(days=days, hours=3 + idx % 5)
        a = workflow.register(db, text=text, author=users[author], source="web" if idx % 4 else "telegram", type=typ,
                              category_id=cats[cat].id, priority=prio, title=title)
        a.created_at = a.updated_at = created
        a.due_at = created + timedelta(days=cats[cat].sla_days)
        a.source = "import" if days > 14 else a.source
        for e in a.events:
            e.created_at = created
        who = users[assignee]
        if a.assignee_id != who.id:  # в датасете ответственный задан на обращение, а не на категорию
            a.assignee_id = who.id
            db.add(Event(appeal=a, kind="assigned", actor_id=users["admin"].id, text=f"Ответственный: {who.name}",
                         data={"assignee_id": who.id}, created_at=created + timedelta(minutes=20)))
        if status == "new":
            continue
        first = created + timedelta(hours=5 + idx * 3 % 30)
        a.first_response_at = first
        a.status = status

        def ev(kind, text="", data=None, at=first, actor=who):
            db.add(Event(appeal=a, kind=kind, actor_id=actor.id if actor else None, text=text, data=data or {}, created_at=at))
            a.updated_at = at

        if status == "clarify":
            ev("question", note, {"from": "new"})
            continue
        ev("status", "", {"from": "new", "to": "review"})
        if status == "review":
            ev("comment", note, at=first + timedelta(hours=2))
        elif status == "in_progress":
            ev("status", note, {"from": "review", "to": "in_progress"}, at=first + timedelta(days=1))
        else:
            end = min(t - timedelta(hours=6), created + timedelta(days=max(2, days // 3)))
            a.closed_at = end
            a.resolution = note
            if status == "done":
                ev("status", "Берем в работу.", {"from": "review", "to": "in_progress"}, at=first + timedelta(days=1))
                ev("status", note, {"from": "in_progress", "to": "done"}, at=end)
            else:
                ev("status", note, {"from": "review", "to": status}, at=end)

    db.flush()
    for num, keys in SUPPORTS.items():
        a = db.scalar(select(Appeal).where(Appeal.number == f"A-{num:03d}"))
        for k in keys:
            db.add(Support(appeal_id=a.id, user_id=users[k].id))
    # уведомления о старых обращениях считаем прочитанными
    old = t - timedelta(days=3)
    for n in db.scalars(select(Notification)):
        ap = db.get(Appeal, n.appeal_id)
        if ap and ap.created_at < old:
            n.read = True
        elif ap:
            n.created_at = ap.created_at
    db.flush()
    workflow.check_deadlines(db)
    db.commit()


def migrate() -> None:
    """Добавить колонки, появившиеся после первого запуска (SQLite сам таблицы не обновляет)."""
    from sqlalchemy import inspect, text
    added = {
        "users": {"bot_state": "JSON", "bot_prefs": "JSON", "ext_ids": "JSON",
                  "gcal": "JSON", "agent_key_hash": "VARCHAR(64)"},
        "departments": {"ext_ids": "JSON"},
        "appeals": {"rating": "INTEGER", "reminded_at": "DATETIME", "gcal": "JSON"},
    }
    for table, columns in added.items():
        have = {c["name"] for c in inspect(engine).get_columns(table)}
        for name, ddl in columns.items():
            if name not in have:
                with engine.begin() as con:
                    con.execute(text(f"ALTER TABLE {table} ADD COLUMN {name} {ddl}"))
    dropped = {"users": ["max_user_id"]}  # колонка снятого второго мессенджера
    for table, columns in dropped.items():
        have = {c["name"] for c in inspect(engine).get_columns(table)}
        for name in columns:
            if name in have:
                with engine.begin() as con:
                    con.execute(text(f"DROP INDEX IF EXISTS ix_{table}_{name}"))
                    con.execute(text(f"ALTER TABLE {table} DROP COLUMN {name}"))


def seed_if_empty() -> None:
    Base.metadata.create_all(engine)
    migrate()
    with SessionLocal() as db:
        if not db.scalar(select(User.id).limit(1)):
            seed(db)


